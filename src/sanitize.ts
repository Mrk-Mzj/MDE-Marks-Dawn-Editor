// Whitelist sanitizer for raw HTML in Markdown (see docs/SPEC.md, "HTML w pliku").
//
// markdown-it passes raw HTML through as it is. To tell the user's tags from
// the ones markdown-it generates, `markRawHtml` renames every tag the user wrote
// (`<u>` becomes `<raw-u>`, a custom element the browser gives no behaviour).
// `sanitize` then walks the parsed result: a `raw-*` element is rebuilt as a
// fresh element when its name is on the whitelist (with only the allowed
// attributes), dropped with its content when it is dangerous, and replaced by
// its content otherwise. Nothing the user wrote is ever serialized back to HTML.

const PREFIX = "raw-";

const ALLOWED_TAGS = new Set(["br", "span", "details", "summary", "sub", "sup", "kbd", "u"]);

// Removed together with everything inside them. <embed> and <frame> are not
// here: they have no content, and as custom elements they would swallow (and
// so delete) the text that follows them; being off the whitelist removes them.
const REMOVED_TAGS = new Set([
  "script",
  "iframe",
  "object",
  "style",
  "form",
  "frameset",
  "applet",
  "noscript",
  "noembed",
  "noframes",
  "template",
  "textarea",
  "select",
  "title",
]);

// Only plain colors: named, hex and rgb()/hsl() without nested functions.
const COLOR = /^(?:#[0-9a-f]{3,8}|[a-z]+|(?:rgb|hsl)a?\([0-9a-z\s.,%/+-]*\))$/i;

/** Marks the tags of raw HTML (an html_inline or html_block token) as user-written. */
export function markRawHtml(html: string): string {
  return (
    html
      .replace(/<(\/?)([a-z])/gi, `<$1${PREFIX}$2`)
      // <br> has no content, but as a custom element it would swallow what follows.
      // [^<>] keeps a long run of unclosed "<br" from making this slow.
      .replace(/<\/?raw-br(?=[\s/>])[^<>]*>/gi, `<${PREFIX}br></${PREFIX}br>`)
  );
}

/** Applies `color` and `background-color` from a style attribute; all else is ignored. */
function copyColors(style: string, target: HTMLElement): void {
  for (const declaration of style.split(";")) {
    const colon = declaration.indexOf(":");
    if (colon < 0) continue;
    const property = declaration.slice(0, colon).trim().toLowerCase();
    const value = declaration.slice(colon + 1).trim();
    // Set through the style object: the Content Security Policy forbids style attributes.
    if ((property === "color" || property === "background-color") && COLOR.test(value) && CSS.supports(property, value)) {
      target.style.setProperty(property, value);
    }
  }
}

function rebuild(source: Element, tag: string): Element {
  const clean = source.ownerDocument.createElement(tag);
  if (tag === "span") copyColors(source.getAttribute("style") ?? "", clean);
  if (tag === "details" && source.hasAttribute("open")) clean.setAttribute("open", "");
  return clean;
}

/** Sanitizes the raw HTML inside `root` (a tree built from `markRawHtml` output) in place. */
export function sanitize(root: ParentNode): void {
  for (const node of Array.from(root.childNodes)) {
    if (node.nodeType === Node.TEXT_NODE) continue;
    if (!(node instanceof Element)) {
      node.remove();
      continue;
    }
    const name = node.localName;
    if (!name.startsWith(PREFIX)) {
      // Generated by markdown-it; only its children can hold raw HTML.
      sanitize(node);
      continue;
    }
    const tag = name.slice(PREFIX.length);
    if (REMOVED_TAGS.has(tag)) {
      node.remove();
      continue;
    }
    sanitize(node);
    const children = Array.from(node.childNodes);
    if (!ALLOWED_TAGS.has(tag)) {
      node.replaceWith(...children);
    } else if (tag === "br") {
      node.replaceWith(rebuild(node, tag), ...children);
    } else {
      const clean = rebuild(node, tag);
      clean.append(...children);
      node.replaceWith(clean);
    }
  }
}
