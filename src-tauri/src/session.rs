//! Session memory in `%APPDATA%\MDE`:
//!
//! - `session.json` — open tabs, scroll positions and settings. Its layout is
//!   owned by the frontend; the backend only stores it.
//! - `window.json` — the window's size, position and maximized state.
//! - `tabs\<id>.txt` — the current text of each open tab, so unsaved edits and
//!   the text of files deleted from disk survive a restart. A tab's file is
//!   removed as soon as the tab is closed.

use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::Mutex;

use serde::{Deserialize, Serialize};
use tauri::{Manager, PhysicalPosition, PhysicalSize, WebviewWindow};

fn data_dir() -> Option<PathBuf> {
    std::env::var_os("APPDATA").map(|dir| PathBuf::from(dir).join("MDE"))
}

fn tabs_dir() -> Option<PathBuf> {
    data_dir().map(|dir| dir.join("tabs"))
}

/// Tab ids are generated by the frontend; anything else could escape the folder.
fn tab_file(id: &str) -> Result<PathBuf, String> {
    let valid = !id.is_empty() && id.len() <= 64 && id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-');
    if !valid {
        return Err(format!("invalid tab id: {id}"));
    }
    tabs_dir().map(|dir| dir.join(format!("{id}.txt"))).ok_or_else(|| "APPDATA is not set".to_owned())
}

/// Writes through a temporary file so a crash never leaves a half-written file.
fn write_atomic(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let tmp = path.with_extension("tmp");
    {
        let mut file = std::fs::File::create(&tmp)?;
        file.write_all(bytes)?;
        file.sync_all()?;
    }
    std::fs::rename(&tmp, path)
}

fn io_error(err: std::io::Error) -> String {
    format!("io:{err}")
}

#[tauri::command]
pub fn read_session() -> Option<String> {
    std::fs::read_to_string(data_dir()?.join("session.json")).ok()
}

#[tauri::command]
pub fn write_session(json: String, geometry: tauri::State<Geometry>) -> Result<(), String> {
    let dir = data_dir().ok_or("APPDATA is not set")?;
    write_atomic(&dir.join("session.json"), json.as_bytes()).map_err(io_error)?;
    let window = *geometry.0.lock().unwrap();
    if let Some(window) = window {
        let json = serde_json::to_vec(&window).map_err(|e| e.to_string())?;
        write_atomic(&dir.join("window.json"), &json).map_err(io_error)?;
    }
    Ok(())
}

#[tauri::command]
pub fn read_tab_text(id: String) -> Option<String> {
    std::fs::read_to_string(tab_file(&id).ok()?).ok()
}

#[tauri::command]
pub fn write_tab_text(id: String, text: String) -> Result<(), String> {
    write_atomic(&tab_file(&id)?, text.as_bytes()).map_err(io_error)
}

#[tauri::command]
pub fn delete_tab_text(id: String) {
    if let Ok(path) = tab_file(&id) {
        let _ = std::fs::remove_file(path);
    }
}

/// Removes the saved text of tabs that are no longer open (e.g. left behind by a crash).
#[tauri::command]
pub fn prune_tab_texts(keep: Vec<String>) {
    let Some(dir) = tabs_dir() else { return };
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        let id = path.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
        if !keep.contains(&id) {
            let _ = std::fs::remove_file(path);
        }
    }
}

/// Size and position of the window when it is neither maximized nor minimized,
/// in physical pixels.
#[derive(Clone, Copy, Serialize, Deserialize)]
pub struct WindowState {
    x: i32,
    y: i32,
    width: u32,
    height: u32,
    maximized: bool,
}

#[derive(Default)]
pub struct Geometry(Mutex<Option<WindowState>>);

fn read_window_state() -> Option<WindowState> {
    let bytes = std::fs::read(data_dir()?.join("window.json")).ok()?;
    serde_json::from_slice(&bytes).ok()
}

/// Puts the (still hidden) window where it was last time, unless that place is
/// no longer on any monitor.
pub fn restore_window(window: &WebviewWindow) {
    let Some(state) = read_window_state() else { return };
    let monitors = window.available_monitors().unwrap_or_default();
    // The title bar must be reachable: a point near the top-left corner has to
    // lie on a monitor.
    let (px, py) = (state.x + 64, state.y + 16);
    let visible = monitors.iter().any(|m| {
        let (pos, size) = (m.position(), m.size());
        px >= pos.x && py >= pos.y && px < pos.x + size.width as i32 && py < pos.y + size.height as i32
    });
    if visible && state.width >= 320 && state.height >= 200 {
        let _ = window.set_size(PhysicalSize::new(state.width, state.height));
        let _ = window.set_position(PhysicalPosition::new(state.x, state.y));
    }
    if state.maximized {
        let _ = window.maximize();
    }
    *window.state::<Geometry>().0.lock().unwrap() = Some(state);
}

/// Remembers the window's normal bounds after it is moved or resized.
pub fn track_window(window: &WebviewWindow) {
    let maximized = window.is_maximized().unwrap_or(false);
    if window.is_minimized().unwrap_or(false) {
        return;
    }
    let geometry = window.state::<Geometry>();
    let mut current = geometry.0.lock().unwrap();
    if maximized {
        if let Some(state) = current.as_mut() {
            state.maximized = true;
        }
        return;
    }
    let (Ok(pos), Ok(size)) = (window.outer_position(), window.inner_size()) else { return };
    *current = Some(WindowState { x: pos.x, y: pos.y, width: size.width, height: size.height, maximized: false });
}
