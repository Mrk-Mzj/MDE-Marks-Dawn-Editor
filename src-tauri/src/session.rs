//! Session memory in `%APPDATA%\MDE`. Every window stores its session in a
//! folder of its own: the default window (MDE started from Windows) in
//! `%APPDATA%\MDE` itself, the window of a tab group in `groups\<id>`
//! (see src/groups.rs). A session folder holds:
//!
//! - `session.json` — open tabs, scroll positions and settings. Its layout is
//!   owned by the frontend; the backend only stores it.
//! - `window.json` — the window's size, position and maximized state.
//! - `tabs\<id>.txt` — the current text of each open tab, so unsaved edits and
//!   the text of files deleted from disk survive a restart. A tab's file is
//!   removed as soon as the tab is closed.

use std::collections::HashMap;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::sync::Mutex;

use serde::{Deserialize, Serialize};
use tauri::{Manager, PhysicalPosition, PhysicalSize, WebviewWindow};

pub fn data_dir() -> Option<PathBuf> {
    std::env::var_os("APPDATA").map(|dir| PathBuf::from(dir).join("MDE"))
}

/// Ids are generated by MDE; anything else could escape the folder.
pub fn valid_id(id: &str) -> bool {
    !id.is_empty() && id.len() <= 64 && id.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-')
}

/// The session folder of the default window (`None`) or of a tab group.
pub fn session_dir(group: Option<&str>) -> Option<PathBuf> {
    let dir = data_dir()?;
    match group {
        None => Some(dir),
        Some(id) if valid_id(id) => Some(dir.join("groups").join(id)),
        Some(_) => None,
    }
}

/// Size and position of the window when it is neither maximized nor minimized,
/// in physical pixels.
#[derive(Clone, Copy, Serialize, Deserialize)]
pub struct WindowState {
    x: i32,
    y: i32,
    width: u32,
    height: u32,
    maximized: bool,
}

/// What the backend knows about one open window.
#[derive(Default)]
pub struct WindowEntry {
    /// The tab group the window works on; `None` for the default window.
    pub group: Option<String>,
    pub geometry: Option<WindowState>,
    /// Files to open once the window's page has started.
    pub files: Vec<String>,
}

/// The open windows by label.
#[derive(Default)]
pub struct Registry(pub Mutex<HashMap<String, WindowEntry>>);

impl Registry {
    pub fn group_of(&self, label: &str) -> Option<String> {
        self.0.lock().unwrap().get(label).and_then(|entry| entry.group.clone())
    }

    /// The label of the window that works on `group` (`None`: the default window).
    pub fn window_of(&self, group: Option<&str>) -> Option<String> {
        let windows = self.0.lock().unwrap();
        windows.iter().find(|(_, entry)| entry.group.as_deref() == group).map(|(label, _)| label.clone())
    }

    fn dir_of(&self, window: &WebviewWindow) -> Result<PathBuf, String> {
        session_dir(self.group_of(window.label()).as_deref()).ok_or_else(|| "APPDATA is not set".to_owned())
    }
}

/// Writes through a temporary file so a crash never leaves a half-written file.
pub fn write_atomic(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    let tmp = path.with_extension("tmp");
    {
        let mut file = std::fs::File::create(&tmp)?;
        file.write_all(bytes)?;
        file.sync_all()?;
    }
    std::fs::rename(&tmp, path)
}

pub fn io_error(err: std::io::Error) -> String {
    format!("io:{err}")
}

fn tab_file(dir: &Path, id: &str) -> Result<PathBuf, String> {
    if !valid_id(id) {
        return Err(format!("invalid tab id: {id}"));
    }
    Ok(dir.join("tabs").join(format!("{id}.txt")))
}

#[tauri::command]
pub fn read_session(window: WebviewWindow, registry: tauri::State<Registry>) -> Option<String> {
    std::fs::read_to_string(registry.dir_of(&window).ok()?.join("session.json")).ok()
}

#[tauri::command]
pub fn write_session(json: String, window: WebviewWindow, registry: tauri::State<Registry>) -> Result<(), String> {
    let dir = registry.dir_of(&window)?;
    write_atomic(&dir.join("session.json"), json.as_bytes()).map_err(io_error)?;
    let geometry = registry.0.lock().unwrap().get(window.label()).and_then(|entry| entry.geometry);
    if let Some(geometry) = geometry {
        let json = serde_json::to_vec(&geometry).map_err(|e| e.to_string())?;
        write_atomic(&dir.join("window.json"), &json).map_err(io_error)?;
    }
    Ok(())
}

#[tauri::command]
pub fn read_tab_text(id: String, window: WebviewWindow, registry: tauri::State<Registry>) -> Option<String> {
    std::fs::read_to_string(tab_file(&registry.dir_of(&window).ok()?, &id).ok()?).ok()
}

#[tauri::command]
pub fn write_tab_text(id: String, text: String, window: WebviewWindow, registry: tauri::State<Registry>) -> Result<(), String> {
    write_atomic(&tab_file(&registry.dir_of(&window)?, &id)?, text.as_bytes()).map_err(io_error)
}

#[tauri::command]
pub fn delete_tab_text(id: String, window: WebviewWindow, registry: tauri::State<Registry>) {
    if let Ok(path) = registry.dir_of(&window).and_then(|dir| tab_file(&dir, &id)) {
        let _ = std::fs::remove_file(path);
    }
}

/// Removes the saved text of tabs that are no longer open (e.g. left behind by a crash).
#[tauri::command]
pub fn prune_tab_texts(keep: Vec<String>, window: WebviewWindow, registry: tauri::State<Registry>) {
    let Ok(dir) = registry.dir_of(&window) else { return };
    let Ok(entries) = std::fs::read_dir(dir.join("tabs")) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        let id = path.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
        if !keep.contains(&id) {
            let _ = std::fs::remove_file(path);
        }
    }
}

/// Empties the default session (its tabs and their texts) and keeps its settings:
/// the default window became a tab group, which took the tabs along.
pub fn clear_default_session() {
    let Some(dir) = session_dir(None) else { return };
    let path = dir.join("session.json");
    if let Some(mut session) = std::fs::read(&path).ok().and_then(|b| serde_json::from_slice::<serde_json::Value>(&b).ok()) {
        if let Some(object) = session.as_object_mut() {
            object.insert("tabs".to_owned(), serde_json::Value::Array(Vec::new()));
            object.insert("active".to_owned(), serde_json::Value::from(0));
            if let Ok(json) = serde_json::to_vec(&session) {
                let _ = write_atomic(&path, &json);
            }
        }
    }
    let _ = std::fs::remove_dir_all(dir.join("tabs"));
}

/// The number of tabs stored in a session folder's `session.json`.
pub fn stored_tab_count(dir: &Path) -> usize {
    std::fs::read(dir.join("session.json"))
        .ok()
        .and_then(|bytes| serde_json::from_slice::<serde_json::Value>(&bytes).ok())
        .and_then(|session| session.get("tabs").and_then(|tabs| tabs.as_array()).map(Vec::len))
        .unwrap_or(0)
}

fn read_window_state(dir: &Path) -> Option<WindowState> {
    let bytes = std::fs::read(dir.join("window.json")).ok()?;
    serde_json::from_slice(&bytes).ok()
}

/// Puts the (still hidden) window where its session's window was last time,
/// unless that place is no longer on any monitor.
pub fn restore_window(window: &WebviewWindow, group: Option<&str>) {
    let Some(state) = session_dir(group).and_then(|dir| read_window_state(&dir)) else { return };
    let monitors = window.available_monitors().unwrap_or_default();
    // The title bar must be reachable: a point near the top-left corner has to
    // lie on a monitor.
    let (px, py) = (state.x + 64, state.y + 16);
    let visible = monitors.iter().any(|m| {
        let (pos, size) = (m.position(), m.size());
        px >= pos.x && py >= pos.y && px < pos.x + size.width as i32 && py < pos.y + size.height as i32
    });
    if visible && state.width >= 320 && state.height >= 200 {
        let _ = window.set_size(PhysicalSize::new(state.width, state.height));
        let _ = window.set_position(PhysicalPosition::new(state.x, state.y));
    }
    if state.maximized {
        let _ = window.maximize();
    }
    if let Some(entry) = window.state::<Registry>().0.lock().unwrap().get_mut(window.label()) {
        entry.geometry = Some(state);
    }
}

/// Remembers the window's normal bounds after it is moved or resized.
pub fn track_window(window: &WebviewWindow) {
    let maximized = window.is_maximized().unwrap_or(false);
    if window.is_minimized().unwrap_or(false) {
        return;
    }
    let registry = window.state::<Registry>();
    let mut windows = registry.0.lock().unwrap();
    let Some(entry) = windows.get_mut(window.label()) else { return };
    if maximized {
        if let Some(state) = entry.geometry.as_mut() {
            state.maximized = true;
        }
        return;
    }
    let (Ok(pos), Ok(size)) = (window.outer_position(), window.inner_size()) else { return };
    entry.geometry = Some(WindowState { x: pos.x, y: pos.y, width: size.width, height: size.height, maximized: false });
}
